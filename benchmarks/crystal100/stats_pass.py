"""Statistics pass: 95% confidence intervals for the gen2 held-out claims.

Reads the committed per-bucket sidecars (bond-order + stereo, gen2) and
the tuning sidecars, and renders `results_stats.md` with:

- pooled proportions with Wilson 95% CIs (ligands treated as Bernoulli
  draws - the optimistic error, reported for reference);
- per-bucket means +/- std with t-based 95% CIs (df = 4: the 60-ligand
  bucket is the experimental unit, so this is the design's honest,
  cluster-level error);
- the head-to-head edges (geometry minus every other runnable baseline,
  per bucket, paired) as t-CIs (df=4) with the pooled-binomial contrast
  alongside;
- the tuning-vs-held-out gap (bond recovery) with normal-approximation
  CIs on the pooled difference.

The YuelBond baseline (run_yuelbond.py, published model + weights) is
merged from its own sidecars when present.  All inputs are the committed
benchmark sidecars; no re-measurement.
"""
from __future__ import annotations

import glob
import json
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "src"))

from benchmark import _env_info

HERE = os.path.dirname(os.path.abspath(__file__))
Z = 1.959964  # 97.5% normal quantile
T_DF4 = 2.776445  # 97.5% t quantile, df = 4 (5 buckets)

METHODS = ["geometry", "openbabel", "distance", "rdDetermineBonds"]
#: order of the head-to-head edge rows (geometry minus baseline)
BASELINES = ["openbabel", "distance", "rdDetermineBonds", "yuelbond"]


def wilson(ok: int, n: int, z: float = Z) -> tuple[float, float]:
    """Wilson 95% CI for a binomial proportion (handles 0/n and n/n)."""
    if n == 0:
        return (float("nan"), float("nan"))
    p = ok / n
    denom = 1 + z * z / n
    center = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (center - half, center + half)


def t_ci(values: list[float]) -> tuple[float, float, float, float]:
    """(mean, std, lo, hi) of a t-CI on n=5 bucket rates (df=4)."""
    mean = sum(values) / len(values)
    var = sum((v - mean) ** 2 for v in values) / (len(values) - 1)
    std = math.sqrt(var)
    half = T_DF4 * std / math.sqrt(len(values))
    return (mean, std, mean - half, mean + half)


def fmt(lo: float, hi: float, pct: bool = True) -> str:
    if math.isnan(lo):
        return "-"
    scale = 100.0 if pct else 1.0
    return f"{scale * lo:.1f} to {scale * hi:.1f}"


def load_bond(tier: str, gen: str) -> list[dict]:
    files = sorted(glob.glob(os.path.join(HERE, f"results_{gen}_{tier}_k*.json")))
    out = []
    for f in files:
        with open(f) as fh:
            out.append(json.load(fh))
    return out


def load_bond_with_yuelbond(tier: str, gen: str) -> tuple[list[dict], bool]:
    """Bond sidecars with the YuelBond method merged in from its own
    sidecars (run_yuelbond.py) - present only when all 5 buckets exist
    and match the bond runs' totals."""
    bond = load_bond(tier, gen)
    yb_files = sorted(glob.glob(
        os.path.join(HERE, f"results_yuelbond_{gen}_{tier}_k*.json")))
    if len(yb_files) != len(bond):
        return bond, False
    for b, f in zip(bond, yb_files):
        with open(f) as fh:
            yb = json.load(fh)
        if yb.get("total") != b["total"] or "yuelbond" not in yb["methods"]:
            return bond, False
        b["methods"]["yuelbond"] = yb["methods"]["yuelbond"]
    return bond, True


def load_stereo(tier: str, gen: str) -> list[dict]:
    files = sorted(glob.glob(os.path.join(HERE, f"results_stereo_{gen}_{tier}_k*.json")))
    out = []
    for f in files:
        with open(f) as fh:
            out.append(json.load(fh))
    return out


def pool_method(buckets: list[dict], method: str, key: str) -> tuple[int, int]:
    ok = sum(b["methods"][method].get(key, 0) for b in buckets)
    total = sum(b["total"] for b in buckets)
    return ok, total


def main() -> None:
    lines: list[str] = []
    add = lines.append

    add("# Statistics pass: 95% confidence intervals (gen2 held-out)")
    add("")
    add(f"Auto-generated by `benchmarks/crystal100/stats_pass.py` - do not edit by hand.  "
        f"Re-run with `uv run python benchmarks/crystal100/stats_pass.py`.  "
        f"Environment: {_env_info()}.")
    add("")
    add("Two error models, both reported: the **pooled Wilson interval** treats the 300 "
        "ligands per tier as independent Bernoulli draws; the **per-bucket t-CI** (df = 4, "
        "n = 5 buckets of 60) treats the bucket as the experimental unit - it is the "
        "design's honest, cluster-level error and is the wider of the two.")
    add("")

    for tier in ["main", "lowres"]:
        bond, have_yb = load_bond_with_yuelbond(tier, "dataset_heldout_gen2")
        methods = METHODS + (["yuelbond"] if have_yb else [])
        baselines = (BASELINES if have_yb
                     else [b for b in BASELINES if b != "yuelbond"])
        stereo = load_stereo(tier, "dataset_heldout_gen2")

        add(f"## Bond-order recovery - {tier} tier (formula AND graph AND AddHs)")
        add("")
        add("| method | pooled | Wilson 95% CI | bucket mean +/- std | t-CI (df=4) |")
        add("|---|---|---|---|---|")
        for m in methods:
            ok, total = pool_method(bond, m, "recovery")
            rates = [b["methods"][m]["recovery"] / b["total"] * 100 for b in bond]
            mean, std, lo, hi = t_ci(rates)
            wlo, whi = wilson(ok, total)
            add(f"| {m} | {ok}/{total} ({100 * ok / total:.1f}%) | {fmt(wlo, whi)} | "
                f"{mean:.1f} +/- {std:.1f} | {fmt(lo, hi, pct=False)} |")
        add("")

        add(f"## Stereo full-string recovery - {tier} tier (comparable subset)")
        add("")
        add("| method | pooled | Wilson 95% CI | bucket mean +/- std | t-CI (df=4) |")
        add("|---|---|---|---|---|")
        for m in ["geometry", "openbabel", "distance"]:
            ok, tot = 0, 0
            rates = []
            for b in stereo:
                comp = b["methods"][m].get("comparable", 0)
                full = b["methods"][m].get("full", 0)
                ok += full
                tot += comp
                rates.append(full / comp * 100 if comp else float("nan"))
            rates = [r for r in rates if not math.isnan(r)]
            if not rates:
                add(f"| {m} | - | - | - | - |")
                continue
            mean, std, lo, hi = t_ci(rates)
            wlo, whi = wilson(ok, tot)
            add(f"| {m} | {ok}/{tot} ({100 * ok / tot:.1f}%) | {fmt(wlo, whi)} | "
                f"{mean:.1f} +/- {std:.1f} | {fmt(lo, hi, pct=False)} |")
        add("")

        add(f"## Per-center R/S - {tier} tier (centers the CCD declares)")
        add("")
        add("| method | pooled | Wilson 95% CI | bucket mean +/- std | t-CI (df=4) |")
        add("|---|---|---|---|---|")
        for m in ["geometry", "openbabel", "distance"]:
            ok, tot = 0, 0
            rates = []
            for b in stereo:
                c = b["methods"][m]["centers"]
                ok += c.get("correct", 0)
                tot += c.get("correct", 0) + c.get("wrong", 0)
                denom = c.get("correct", 0) + c.get("wrong", 0)
                rates.append(c.get("correct", 0) / denom * 100 if denom else float("nan"))
            rates = [r for r in rates if not math.isnan(r)]
            if not rates:
                add(f"| {m} | - | - | - | - |")
                continue
            mean, std, lo, hi = t_ci(rates)
            wlo, whi = wilson(ok, tot)
            add(f"| {m} | {ok}/{tot} ({100 * ok / tot:.1f}%) | {fmt(wlo, whi)} | "
                f"{mean:.1f} +/- {std:.1f} | {fmt(lo, hi, pct=False)} |")
        add("")

        add(f"## E/Z - {tier} tier (double bonds the CCD declares)")
        add("")
        add("| method | correct | wrong | pooled | Wilson 95% CI |")
        add("|---|---|---|---|---|")
        for m in ["geometry", "openbabel", "distance"]:
            ok = wrong = 0
            for b in stereo:
                ez = b["methods"][m].get("ez", {})
                ok += ez.get("correct", 0)
                wrong += ez.get("wrong", 0)
            if ok + wrong == 0:
                add(f"| {m} | - | - | - | - |")
                continue
            wlo, whi = wilson(ok, ok + wrong)
            add(f"| {m} | {ok} | {wrong} | {100 * ok / (ok + wrong):.1f}% | {fmt(wlo, whi)} |")
        add("")

        add(f"## Stereo coverage - {tier} tier")
        add("")
        cov = [b["stereo_entries"] / b["total"] * 100 for b in stereo]
        mean, std, lo, hi = t_ci(cov)
        wlo, whi = wilson(sum(b["stereo_entries"] for b in stereo),
                          sum(b["total"] for b in stereo))
        add("| pooled | Wilson 95% CI | bucket mean +/- std | t-CI (df=4) |")
        add("|---|---|---|---|")
        add(f"| {sum(b['stereo_entries'] for b in stereo)}/"
            f"{sum(b['total'] for b in stereo)} ({mean:.1f}%) | {fmt(wlo, whi)} | "
            f"{mean:.1f} +/- {std:.1f} | {fmt(lo, hi, pct=False)} |")
        add("")

        add(f"## Head-to-head edges vs geometry - {tier} tier")
        add("")
        add("| edge | bucket mean (paired) | t-CI (df=4) | pooled diff | "
            "binomial 95% CI |")
        add("|---|---|---|---|---|")
        for base in baselines:
            diffs = []
            for b in bond:
                g = b["methods"]["geometry"]["recovery"] / b["total"]
                o = b["methods"][base]["recovery"] / b["total"]
                diffs.append((g - o) * 100)
            mean, std, lo, hi = t_ci(diffs)
            ok_g, tot_g = pool_method(bond, "geometry", "recovery")
            ok_o, tot_o = pool_method(bond, base, "recovery")
            pg, po = ok_g / tot_g, ok_o / tot_o
            se_pool = math.sqrt(pg * (1 - pg) / tot_g + po * (1 - po) / tot_o)
            add(f"| geometry - {base} | {mean:.1f} | {fmt(lo, hi, pct=False)} | "
                f"{100 * (pg - po):.1f} | "
                f"{fmt(100 * (pg - po - Z * se_pool), 100 * (pg - po + Z * se_pool), pct=False)} |")
        add("")
        add("The t-CI on the paired bucket differences is the design's honest interval for "
            "each edge; the binomial CI pools the 300 ligands as independent and is reported "
            "to show how much the cluster effect widens it.")
        add("")

    # Tuning vs held-out gap (bond recovery)
    tuning = {}
    for tier, name in (("main", "results.json"),
                       ("lowres", "results_dataset_res250-300.json")):
        with open(os.path.join(HERE, name), encoding="utf-8") as fh:
            tuning[tier] = json.load(fh)
    add("## Tuning vs held-out gap (bond recovery)")
    add("")
    add("| tier | method | tuning | held-out | gap | 95% CI (normal approx) |")
    add("|---|---|---|---|---|---|")
    for tier in ["main", "lowres"]:
        t = tuning[tier]
        held, have_yb = load_bond_with_yuelbond(tier, "dataset_heldout_gen2")
        for m in METHODS + (["yuelbond"] if have_yb else []):
            if m == "yuelbond" and "yuelbond" not in t["methods"]:
                continue  # tuning set was never run with YuelBond
            tok = t["methods"].get(m, {}).get("recovery", 0)
            tt = t["total"]
            hok, ht = pool_method(held, m, "recovery")
            pt, ph = tok / tt, hok / ht
            se = math.sqrt(pt * (1 - pt) / tt + ph * (1 - ph) / ht)
            gap = ph - pt
            add(f"| {tier} | {m} | {tok}/{tt} ({100 * pt:.1f}%) | {hok}/{ht} "
                f"({100 * ph:.1f}%) | {100 * gap:+.1f} | {fmt(100 * (gap - Z * se), 100 * (gap + Z * se), pct=False)} |")
    add("")
    add("Normal approximation on the pooled proportions, z = 1.96; the held-out side is "
        "clustered, so treat intervals touching zero as consistent with no gap.")

    with open(os.path.join(HERE, "results_stats.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
